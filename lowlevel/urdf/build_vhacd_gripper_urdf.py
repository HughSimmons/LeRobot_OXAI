"""Build a sim-only copy of so101_with_mount.urdf whose gripper collides like the real one.

PyBullet collides with the convex hull of each mesh on a moving link. The gripper body
(wrist_roll_follower_so101_v1.stl, which includes the fixed jaw) is far from convex, so its
hull fills in the space between the jaws: on the c3->d6 click pick (2026-11-16) the fixed jaw
touched the rook 12-15 mm from any real plastic, at an angle the real jaw never makes.

This splits the gripper body and the moving jaw into several convex parts with V-HACD
(PyBullet's built-in p.vhacd), writes them to urdf/vhacd_gripper/, and writes
urdf/so101_with_mount_vhacd_gripper.urdf with only those two collision meshes swapped. Visuals,
inertias, joints and every other link are unchanged. PyBullet loads each object in a
multi-object .obj collision mesh as its own convex hull.

multisim_chess_fast.py uses it when SIM_GRIPPER_MODEL=realistic.

Usage (IKsim_mj env): python lowlevel/urdf/build_vhacd_gripper_urdf.py
"""

import re
import struct
import sys
import tempfile
from pathlib import Path

import numpy as np
import pybullet as p

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
import paths  # noqa: E402

MESHES = ("wrist_roll_follower_so101_v1", "moving_jaw_so101_v1")
OUT_DIR = paths.URDF_VHACD_GRIPPER_PATH.parent / "vhacd_gripper"
# Tested 2026-11-16: 10 parts for the gripper body, 14 for the moving jaw; their surfaces sit a
# median 0.3-0.5 mm from the real mesh (95% within 1.7 mm). Resolution 4e6 / concavity 1e-4 gave
# 34 and 18 parts for little gain and would slow every sim step.
VHACD_SETTINGS = dict(
    resolution=1_000_000,
    concavity=0.0005,
    maxNumVerticesPerCH=64,
    minVolumePerCH=1e-7,
    depth=32,
    planeDownsampling=4,
    convexhullDownsampling=4,
)


def load_stl(path: Path) -> np.ndarray:
    """Triangles (n, 3, 3) from an ASCII or binary STL."""
    data = path.read_bytes()
    if data[:5] == b"solid" and b"facet" in data[:400]:
        v = [
            list(map(float, line.split()[1:4]))
            for line in data.decode(errors="ignore").splitlines()
            if line.strip().startswith("vertex")
        ]
        return np.array(v).reshape(-1, 3, 3)
    n = struct.unpack("<I", data[80:84])[0]
    rec = np.frombuffer(
        data[84:84 + 50 * n],
        dtype=np.dtype([("n", "<f4", 3), ("v", "<f4", (3, 3)), ("a", "<u2")]),
    )
    return rec["v"].astype(float)


def write_obj(triangles: np.ndarray, path: Path) -> None:
    verts, faces = np.unique(np.round(triangles.reshape(-1, 3), 9), axis=0, return_inverse=True)
    with path.open("w") as f:
        f.writelines(f"v {x:.9f} {y:.9f} {z:.9f}\n" for x, y, z in verts)
        f.writelines(f"f {a + 1} {b + 1} {c + 1}\n" for a, b, c in faces.reshape(-1, 3))


def count_parts(obj_path: Path) -> int:
    return sum(1 for line in obj_path.open() if line.startswith(("o ", "g ")))


def swap_collision_meshes(urdf_text: str, replacements: dict[str, str]) -> str:
    """Replace mesh filenames inside <collision> blocks only (visuals keep the STLs)."""
    def fix_block(match: re.Match) -> str:
        block = match.group(0)
        for stl_name, new_path in replacements.items():
            block = re.sub(
                r'filename="[^"]*/' + re.escape(stl_name) + r'"',
                f'filename="{new_path}"',
                block,
            )
        return block

    new_text, n_blocks = re.subn(r"<collision>.*?</collision>", fix_block, urdf_text, flags=re.S)
    for stl_name, new_path in replacements.items():
        if f'filename="{new_path}"' not in new_text:
            raise RuntimeError(f"no <collision> mesh for {stl_name} found in {paths.URDF_PATH}")
    return new_text


def main() -> None:
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    p.connect(p.DIRECT)
    replacements = {}
    with tempfile.TemporaryDirectory() as tmp:
        for name in MESHES:
            src = Path(tmp) / f"{name}.obj"
            dst = OUT_DIR / f"{name}_vhacd.obj"
            write_obj(load_stl(paths.ASSETS_DIR / f"{name}.stl"), src)
            p.vhacd(str(src), str(dst), str(Path(tmp) / "vhacd_log.txt"), **VHACD_SETTINGS)
            print(f"{name}: {count_parts(dst)} convex parts -> {dst}")
            # Relative to the URDF, like its other mesh paths.
            replacements[f"{name}.stl"] = dst.relative_to(paths.URDF_VHACD_GRIPPER_PATH.parent).as_posix()
    p.disconnect()

    urdf_text = swap_collision_meshes(paths.URDF_PATH.read_text(), replacements)
    header = (
        "<!-- Generated by build_vhacd_gripper_urdf.py from "
        f"{paths.URDF_PATH.name}: gripper collision meshes split into convex parts (V-HACD). "
        "Edit the source URDF and re-run the script instead of editing this file. -->\n"
    )
    if urdf_text.startswith("<?xml"):
        first_line_end = urdf_text.index("\n") + 1
        urdf_text = urdf_text[:first_line_end] + header + urdf_text[first_line_end:]
    else:
        urdf_text = header + urdf_text
    paths.URDF_VHACD_GRIPPER_PATH.write_text(urdf_text)
    print(f"wrote {paths.URDF_VHACD_GRIPPER_PATH}")


if __name__ == "__main__":
    main()
